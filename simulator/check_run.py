"""Check a ground-truth log against config.yaml: exact visitor count, shares within 3 standard errors.

uv run python -m simulator.check_run simulator/runs/real_run.jsonl --expected 500
"""
import argparse
import math
import sys
from pathlib import Path

from simulator.behavior import load_config
from simulator.ground_truth import read

SHARES = ("share_B", "share_accept", "share_reject", "share_ignore", "share_ad_blocker")


def summarize(lines) -> dict:
    ends = [line for line in lines if line["event"] == "visit_end"]
    n = len(ends)

    def share(test) -> float:
        return sum(1 for e in ends if test(e)) / n if n else 0.0

    known = [e for e in ends if e["variant"] is not None]  # failed before the site drew a variant
    return {
        "visitors": n,
        "variant_known": len(known),
        "share_B": sum(1 for e in known if e["variant"] == "B") / len(known) if known else 0.0,
        "share_accept": share(lambda e: e["banner"] == "accept"),
        "share_reject": share(lambda e: e["banner"] == "reject"),
        "share_ignore": share(lambda e: e["banner"] == "ignore"),
        "share_ad_blocker": share(lambda e: e["ad_blocker"]),
        "error_rate": share(lambda e: e["status"] == "error"),
        "cookieless_visitors": sum(1 for e in ends if e["banner"] in ("reject", "ignore")
                                   and not e["ad_blocker"] and e["status"] == "ok"),
    }


def _expected_shares(cfg: dict) -> dict:
    banner = cfg["banner"]
    return {"share_B": 0.5, "share_accept": banner["accept"], "share_reject": banner["reject"],
            "share_ignore": banner["ignore"], "share_ad_blocker": cfg["ad_blocker"]}


def problems(summary: dict, cfg: dict, expected_visitors: int) -> list[str]:
    found = []
    n = summary["visitors"]
    if n != expected_visitors:
        found.append(f"visitors: {n}, expected {expected_visitors}")
    for key, p in _expected_shares(cfg).items():
        base = summary["variant_known"] if key == "share_B" else n
        bound = 3 * math.sqrt(p * (1 - p) / max(base, 1))
        if abs(summary[key] - p) > bound:
            found.append(f"{key}: {summary[key]:.4f}, expected {p} ± {bound:.4f}")
    max_rate = cfg["real"]["max_error_rate"]
    if summary["error_rate"] >= max_rate:
        found.append(f"error_rate: {summary['error_rate']:.4f}, must stay below {max_rate}")
    return found


def client_id_match_sql(lines, table: str) -> str:
    """BigQuery console query: how many logged GA4 client IDs appear as user_pseudo_id in the export."""
    ids = sorted({line["ga_client_id"] for line in lines if line["ga_client_id"]})
    array = "[" + ", ".join(f"'{i}'" for i in ids) + "]" if ids else "ARRAY<STRING>[]"
    return f"""-- Real-run visitors who accepted cookies without an ad blocker, matched to the GA4 export.
-- Generated by simulator.check_run.client_id_match_sql; {len(ids)} client IDs.
WITH logged AS (
  SELECT id FROM UNNEST({array}) AS id
),
exported AS (
  SELECT DISTINCT user_pseudo_id AS id FROM {table}
)
SELECT
  COUNT(*) AS logged,
  COUNT(exported.id) AS found,
  ROUND(SAFE_DIVIDE(COUNT(exported.id), COUNT(*)), 3) AS share_found
FROM logged
LEFT JOIN exported ON logged.id = exported.id
"""


def main() -> None:
    parser = argparse.ArgumentParser(description="Check a ground-truth log against config.yaml.")
    parser.add_argument("log", type=Path)
    parser.add_argument("--expected", type=int, required=True, help="exact number of visitors")
    args = parser.parse_args()
    summary = summarize(read(args.log))
    for key, value in summary.items():
        print(f"{key}: {value:.4f}" if isinstance(value, float) else f"{key}: {value}")
    found = problems(summary, load_config(), args.expected)
    print("\n".join(found) if found else "OK")
    sys.exit(1 if found else 0)


if __name__ == "__main__":
    main()
